CREATE TABLE IF NOT EXISTS bead_color (
  id    INT PRIMARY KEY AUTO_INCREMENT,
  code  VARCHAR(10)      NOT NULL UNIQUE COMMENT '色码编号，如A1',
  hex   CHAR(7)          NOT NULL COMMENT '十六进制颜色，如#FAF5CD',
  r     TINYINT UNSIGNED NOT NULL,
  g     TINYINT UNSIGNED NOT NULL,
  b     TINYINT UNSIGNED NOT NULL,
  INDEX idx_code (code)
) DEFAULT CHARSET=utf8mb4 COMMENT='拼豆色码表';

CREATE TABLE IF NOT EXISTS bead_palette (
  id     INT PRIMARY KEY AUTO_INCREMENT,
  name   VARCHAR(10) NOT NULL UNIQUE COMMENT '色盘编号，如1、A、8_MARD',
  remark VARCHAR(50) DEFAULT '' COMMENT '备注'
) DEFAULT CHARSET=utf8mb4 COMMENT='色盘表';

CREATE TABLE IF NOT EXISTS bead_palette_color (
  palette_id INT NOT NULL COMMENT '色盘ID',
  color_id   INT NOT NULL COMMENT '色码ID',
  PRIMARY KEY (palette_id, color_id)
) DEFAULT CHARSET=utf8mb4 COMMENT='色盘色码关联表';

CREATE TABLE IF NOT EXISTS bead_brand (
  id   INT PRIMARY KEY AUTO_INCREMENT,
  name VARCHAR(20) NOT NULL UNIQUE COMMENT '品牌名称'
) DEFAULT CHARSET=utf8mb4 COMMENT='拼豆品牌表';

CREATE TABLE IF NOT EXISTS bead_brand_kit (
  id          INT PRIMARY KEY AUTO_INCREMENT,
  brand_id    INT NOT NULL COMMENT '品牌ID',
  color_count INT NOT NULL COMMENT '套装色数',
  palette_ids VARCHAR(200) NOT NULL COMMENT '色盘name列表，逗号分隔',
  UNIQUE KEY uk_brand_count (brand_id, color_count)
) DEFAULT CHARSET=utf8mb4 COMMENT='品牌套装表';

